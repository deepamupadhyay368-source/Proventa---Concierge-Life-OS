/**
 * PROVENTA — PART 4: REAL ESTATE INTELLIGENCE REPORT GENERATOR
 * Produces structured, auditable payloads for all 7 institutional report types
 * with mandatory methodology, data sources, confidence indicators, and disclaimers.
 */

export type RealEstateReportType =
  | 'PROPERTY_INTELLIGENCE'
  | 'PROJECT_INTELLIGENCE'
  | 'LOCALITY_INTELLIGENCE'
  | 'INVESTMENT_FEASIBILITY'
  | 'PROPERTY_VALUATION'
  | 'PORTFOLIO_PERFORMANCE'
  | 'MARKET_COMPARISON';

export interface StructuredIntelligenceReport {
  reportReference: string;
  reportType: RealEstateReportType;
  generatedAtIso: string;
  subjectTitle: string;
  geography: string;
  metrics: Record<string, unknown>;
  methodology: string;
  dataSources: string[];
  confidenceLevel: 'HIGH' | 'MODERATE' | 'LOW' | 'INSUFFICIENT_DATA';
  assumptions: string[];
  limitations: string[];
  nonCertifiedDisclaimer: string;
}

export function buildRealEstateReport(params: {
  reportType: RealEstateReportType;
  subjectTitle: string;
  geography?: string;
  metrics: Record<string, unknown>;
  methodology: string;
  dataSources: string[];
  confidenceLevel: 'HIGH' | 'MODERATE' | 'LOW' | 'INSUFFICIENT_DATA';
  assumptions?: string[];
  limitations?: string[];
}): StructuredIntelligenceReport {
  const code = `PV-RPT-${new Date().getFullYear()}-${Math.random().toString(36).substring(2, 8).toUpperCase()}`;

  return {
    reportReference: code,
    reportType: params.reportType,
    generatedAtIso: new Date().toISOString(),
    subjectTitle: params.subjectTitle,
    geography: params.geography || 'Ahmedabad & Gandhinagar, Gujarat',
    metrics: params.metrics,
    methodology: params.methodology,
    dataSources: params.dataSources.length ? params.dataSources : ['User-supplied inputs (unverified)'],
    confidenceLevel: params.confidenceLevel,
    assumptions: params.assumptions || ['Carpet-area normalization per Gujarat RERA standards.'],
    limitations: params.limitations || [
      'Subject to availability of verified sub-registrar transaction records and micro-market liquidity.',
    ],
    nonCertifiedDisclaimer:
      'IMPORTANT: Automated indicative intelligence and valuation outputs generated by PROVENTA do NOT constitute a statutory certified valuation under the Wealth Tax Act, bank mortgage appraisal, legal title clearance, or personalised financial advice.',
  };
}
