import { describe, it, expect } from 'vitest';
import { AdapterRegistry } from '@/lib/orchestration/adapters';
import { DiningAgent } from '@/lib/orchestration/agents';
import { OptionProposal, ExecutionOutput } from '@/lib/orchestration/types';

describe('Provider Identity & Execution Integrity', () => {
  describe('1. Adapter Identity & Registry Guarantees', () => {
    it('ensures all registered adapters have non-empty, unique providerIds', () => {
      const adapters = AdapterRegistry.getAllAdapters();
      expect(adapters.length).toBeGreaterThanOrEqual(6);

      const ids = new Set<string>();
      for (const adapter of adapters) {
        expect(adapter.providerId).toBeDefined();
        expect(typeof adapter.providerId).toBe('string');
        expect(adapter.providerId.trim().length).toBeGreaterThan(0);
        expect(ids.has(adapter.providerId)).toBe(false);
        ids.add(adapter.providerId);
      }
    });

    it('retrieves adapters directly by providerId with zero ambiguity', () => {
      const swiggy = AdapterRegistry.getAdapterById('swiggy_dineout');
      expect(swiggy).toBeDefined();
      expect(swiggy?.providerId).toBe('swiggy_dineout');

      const amd = AdapterRegistry.getAdapterById('ahmedabad_verified');
      expect(amd).toBeDefined();
      expect(amd?.providerId).toBe('ahmedabad_verified');

      const flights = AdapterRegistry.getAdapterById('amadeus_flights');
      expect(flights).toBeDefined();
      expect(flights?.providerId).toBe('amadeus_flights');

      const cinema = AdapterRegistry.getAdapterById('cinema_pvr_inox');
      expect(cinema).toBeDefined();
      expect(cinema?.providerId).toBe('cinema_pvr_inox');

      const mockDining = AdapterRegistry.getAdapterById('mock_dining');
      expect(mockDining).toBeDefined();
      expect(mockDining?.providerId).toBe('mock_dining');

      const nonExistent = AdapterRegistry.getAdapterById('non_existent_provider_xyz');
      expect(nonExistent).toBeUndefined();
    });
  });

  describe('2. Proposal Provider Identity Stamp', () => {
    it('stamps proposals generated by Ahmedabad Verified adapter with its providerId and venueId', async () => {
      const amdAdapter = AdapterRegistry.getAdapterById('ahmedabad_verified')!;
      const proposals = await amdAdapter.search({
        category: 'dining',
        rawInput: 'Agashiye dinner table',
      });

      expect(proposals.length).toBeGreaterThan(0);
      for (const prop of proposals) {
        expect(prop.providerId).toBe('ahmedabad_verified');
        expect(prop.venueId).toBeDefined();
        expect(prop.environment).toBe('REAL');
      }
    });

    it('stamps proposals generated by Swiggy adapter with providerId swiggy_dineout', async () => {
      const swiggy = AdapterRegistry.getAdapterById('swiggy_dineout')!;
      const proposals = await swiggy.search({
        category: 'dining',
        rawInput: 'Swiggy dinner',
      });

      expect(proposals.length).toBeGreaterThan(0);
      for (const prop of proposals) {
        expect(prop.providerId).toBe('swiggy_dineout');
      }
    });

    it('stamps proposals generated by Flights adapter with providerId amadeus_flights', async () => {
      const flights = AdapterRegistry.getAdapterById('amadeus_flights')!;
      const proposals = await flights.search({
        category: 'flights',
        rawInput: 'Flight to Mumbai',
      });

      expect(proposals.length).toBeGreaterThan(0);
      for (const prop of proposals) {
        expect(prop.providerId).toBe('amadeus_flights');
      }
    });

    it('stamps proposals generated by Cinema adapter with providerId cinema_pvr_inox', async () => {
      const cinema = AdapterRegistry.getAdapterById('cinema_pvr_inox')!;
      const proposals = await cinema.search({
        category: 'movies',
        rawInput: 'IMAX Laser tickets',
      });

      expect(proposals.length).toBeGreaterThan(0);
      for (const prop of proposals) {
        expect(prop.providerId).toBe('cinema_pvr_inox');
      }
    });
  });

  describe('3. Execution Provider Routing Integrity', () => {
    const mockTask = {
      id: 'task-test-001',
      userId: 'user-001',
      category: 'dining',
      partySize: 2,
      targetDate: new Date(),
    };

    it('executes strictly through the adapter matching proposal.providerId', async () => {
      const diningAgent = new DiningAgent();

      // Case A: Ahmedabad Verified Proposal
      const amdProposal: OptionProposal = {
        id: 'prop-amd-test',
        providerId: 'ahmedabad_verified',
        providerName: 'Agashiye - The House of MG',
        title: 'Agashiye Heritage Dining',
        description: 'Heritage Rooftop Terrace',
        priceAmount: 3900,
        priceCurrency: 'INR',
        priceFormatted: '₹3,900',
        environment: 'REAL',
        isMock: false,
      };

      const amdResult = await diningAgent.execute(mockTask, amdProposal);
      expect(amdResult.success).toBe(true);
      expect(amdResult.providerId).toBe('ahmedabad_verified');
      expect(amdResult.environment).toBe('REAL');
      expect(amdResult.status).toBe('AWAITING_CONCIERGE_CALL');
      expect(amdResult.externalReferenceId).toBeUndefined();
      expect(amdResult.confirmedDetails.dispatchPayload).toBeDefined();
      expect(amdResult.confirmedDetails.dispatchPayload.venuePhone).toBeTruthy();

      // Case B: Swiggy Dineout Proposal (must execute through swiggy, NOT ahmedabad_verified)
      const swiggyProposal: OptionProposal = {
        id: 'prop-swiggy-test',
        providerId: 'swiggy_dineout',
        providerName: 'Swiggy Gourmet Reserve',
        title: 'Swiggy Gourmet Reserve Dining',
        description: 'Curated dining via Swiggy',
        priceAmount: 4200,
        priceCurrency: 'INR',
        priceFormatted: '₹4,200',
        environment: 'SANDBOX',
        isMock: true,
      };

      const swiggyResult = await diningAgent.execute(mockTask, swiggyProposal);
      expect(swiggyResult.success).toBe(true);
      expect(swiggyResult.providerId).toBe('swiggy_dineout');
      expect(swiggyResult.environment).toBe('SANDBOX');
      expect(swiggyResult.externalReferenceId).toContain('SWIGGY');

      // Case C: Mock Dining Proposal
      const mockDineProposal: OptionProposal = {
        id: 'prop-mock-test',
        providerId: 'mock_dining',
        providerName: 'OpenTable Test Venue',
        title: 'OpenTable Dining',
        description: 'OpenTable mock reservation',
        priceAmount: 2000,
        priceCurrency: 'INR',
        priceFormatted: '₹2,000',
        environment: 'SANDBOX',
        isMock: true,
      };

      const mockResult = await diningAgent.execute(mockTask, mockDineProposal);
      expect(mockResult.success).toBe(true);
      expect(mockResult.providerId).toBe('mock_dining');
      expect(mockResult.externalReferenceId).toContain('DIN-');
    });

    it('safely fails execution when proposal.providerId is missing or unknown', async () => {
      const diningAgent = new DiningAgent();

      // Missing providerId
      const proposalWithoutProviderId: any = {
        id: 'prop-broken-1',
        title: 'Unknown Dining',
        providerName: 'Mystery Restaurant',
        description: 'Missing providerId property',
        priceAmount: 1000,
        priceCurrency: 'INR',
        priceFormatted: '₹1,000',
      };

      const resultMissing = await diningAgent.execute(mockTask, proposalWithoutProviderId);
      expect(resultMissing.success).toBe(false);
      expect(resultMissing.errorMessage).toContain('does not specify a valid providerId');

      // Unknown providerId
      const proposalUnknownProvider: OptionProposal = {
        id: 'prop-broken-2',
        providerId: 'non_existent_provider_xyz',
        title: 'Phantom Dining',
        providerName: 'Phantom Provider',
        description: 'Invalid providerId',
        priceAmount: 1000,
        priceCurrency: 'INR',
        priceFormatted: '₹1,000',
      };

      const resultUnknown = await diningAgent.execute(mockTask, proposalUnknownProvider);
      expect(resultUnknown.success).toBe(false);
      expect(resultUnknown.errorMessage).toContain("Provider adapter 'non_existent_provider_xyz' not found");
    });

    it('prevents cross-domain adapter mismatches', async () => {
      const diningAgent = new DiningAgent(); // Domain is 'dining'

      // Attempt to execute a flight proposal through dining agent
      const flightProposal: OptionProposal = {
        id: 'prop-cross-domain',
        providerId: 'amadeus_flights', // Flights adapter does not support 'dining'
        providerName: 'Air India',
        title: 'Flight Ticket',
        description: 'Flight to Delhi',
        priceAmount: 8000,
        priceCurrency: 'INR',
        priceFormatted: '₹8,000',
      };

      const result = await diningAgent.execute(mockTask, flightProposal);
      expect(result.success).toBe(false);
      expect(result.errorMessage).toContain("does not support domain category 'dining'");
    });
  });

  describe('4. Verification Routing Integrity', () => {
    it('strictly routes verification to the adapter identified by execution.providerId', async () => {
      const diningAgent = new DiningAgent();

      // AMD Execution
      const amdExec: ExecutionOutput = {
        success: true,
        providerId: 'ahmedabad_verified',
        externalReferenceId: 'AGS-VERIFIED-99',
        providerName: 'Agashiye',
        status: 'CONFIRMED',
        confirmedDetails: {},
        environment: 'REAL',
      };

      const amdVerify = await diningAgent.verify(amdExec);
      expect(amdVerify.verified).toBe(true);
      expect(amdVerify.status).toBe('CONFIRMED');
      expect(amdVerify.auditTrail).toContain('Proventa Ahmedabad Verified Partner Desk');

      // Swiggy Execution
      const swiggyExec: ExecutionOutput = {
        success: true,
        providerId: 'swiggy_dineout',
        externalReferenceId: '[SANDBOX]-SWIGGY-8888',
        providerName: 'Swiggy Gourmet',
        status: 'CONFIRMED',
        confirmedDetails: {},
        environment: 'SANDBOX',
      };

      const swiggyVerify = await diningAgent.verify(swiggyExec);
      expect(swiggyVerify.verified).toBe(true);
      expect(swiggyVerify.status).toBe('CONFIRMED');
      expect(swiggyVerify.auditTrail).toContain('Swiggy Partner Simulation Gateway');
    });

    it('safely fails verification when execution.providerId is missing or invalid', async () => {
      const diningAgent = new DiningAgent();

      const execMissingProviderId: ExecutionOutput = {
        success: true,
        externalReferenceId: 'SOME-REF',
        providerName: 'Unknown',
        status: 'CONFIRMED',
        confirmedDetails: {},
      };

      const resultMissing = await diningAgent.verify(execMissingProviderId);
      expect(resultMissing.verified).toBe(false);
      expect(resultMissing.status).toBe('FAILED');
      expect(resultMissing.auditTrail).toContain('missing providerId');

      const execInvalidProviderId: ExecutionOutput = {
        success: true,
        providerId: 'unknown_provider_123',
        externalReferenceId: 'SOME-REF',
        providerName: 'Unknown',
        status: 'CONFIRMED',
        confirmedDetails: {},
      };

      const resultInvalid = await diningAgent.verify(execInvalidProviderId);
      expect(resultInvalid.verified).toBe(false);
      expect(resultInvalid.status).toBe('FAILED');
      expect(resultInvalid.auditTrail).toContain("Provider adapter 'unknown_provider_123' not found");
    });
  });
});
